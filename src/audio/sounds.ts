export type SfxName = keyof typeof SFX;

/** 結果画面に入ったときの SE。 */
export function sfxForReport(r: Pick<ScoreReport, "passed" | "encore">): SfxName {
  if (r.encore) return "encore";
  return r.passed ? "pass" : "fail";
}

